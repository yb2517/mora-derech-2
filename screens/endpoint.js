// הכתובת האחת של המסכים. משימה 3 בתוכנית שלב 2.
//
// המקור: מפה 4.1 (המעטפות), מבחן מבנה 03 ("כל מסך פונה לכתובת אחת
// ומצהיר מי הוא"), וחוק ברזל 1 ("כל בקשה נוסעת בשתי המעטפות של
// CORE-01. אף מודול אינו מגדיר מעטפה משלו").
//
// הקובץ הזה אינו מייבא דבר, וזו אינה הזנחה: הוא מקבל את הפונקציה
// שמטפלת בבקשה בהזרקה, ולכן הוא אינו מכיר את ה-Orchestrator, אינו
// מכיר את שכבת הנתונים ואינו מכיר אף מודול. מסך שמייבא אותו אינו
// גורר איתו דבר.
//
// מה הוא כן עושה, ואת זה בלבד:
//   1. חותם את שדה השפה על המעטפה.
//   2. מעביר לכתובת האחת.
//   3. מחזיר את מעטפת התשובה כמות שהיא.
//
// מה הוא אינו עושה: אינו חותם את שם הפונה. המסך הוא שמצהיר מי הוא,
// לפי מבחן 03, ולכן שדה from מגיע מהמסך ולא מכאן. כתובת שחותמת את
// הזהות בעצמה הופכת את ההצהרה לבלתי ניתנת לבדיקה.
//
// וגם: אינו מפרש את התשובה, אינו מתרגם קוד שגיאה לנוסח, ואינו
// מחליט מה לעשות בכשל. אלה של המסך, שקורא את הנוסח לאדם מטבלת
// ה-reference (BL-12).

// מפה 4.1: "lang בגרסה 1 מקבל את הערך he בלבד; רשימה סגורה תיכנס
// לטבלת ה-reference כשתתווסף שפה". כל עוד יש שפה אחת אין כאן ערך
// משתנה אלא קבוע של הגרסה, והוא יושב בנקודה אחת: הכתובת שחותמת
// את המעטפה. הוספת שפה היא מפתח בטבלה, לפי אותה שורה במפה.
const LANG = 'he';

/**
 * בונה את הכתובת האחת.
 *
 * @param {object} options
 * @param {(request: object) => Promise<object>} options.handle הפונקציה
 *   שמקבלת מעטפת בקשה ומחזירה מעטפת תשובה. בהרכבה זהו CORE-02.
 *   בבדיקה זו פונקציה שמתעדת מה קיבלה, ולכן הכתובת נבדקת לבדה.
 * @returns {(request: object) => Promise<object>} send
 */
export function createEndpoint({ handle } = {}) {
  if (typeof handle !== 'function') {
    throw new Error('הכתובת האחת זקוקה לפונקציה שמטפלת בבקשה');
  }

  return async function send(request) {
    if (!request || typeof request !== 'object' || Array.isArray(request)) {
      throw new Error('מעטפת בקשה חייבת להיות אובייקט');
    }

    // החתימה אחרונה, ולכן מסך אינו יכול לשלוח שפה אחרת בטעות.
    // מעטפה חסרה או שגויה בכל שדה אחר עוברת כמות שהיא: האימות הוא
    // של CORE-01 ולא כאן, וכפילות אימות פירושה שני מקומות שיכולים
    // להיפרד זה מזה.
    return handle({ ...request, lang: LANG });
  };
}
